using System.Text;

namespace ComParta.Notices;

/// <summary>
/// Writes THIRD-PARTY-NOTICES.txt: the same parts always give the same text (sorted, LF line endings,
/// no dates), so the committed file can be compared with a fresh one.
/// </summary>
public static class NoticesWriter
{
    public const string FileName = "THIRD-PARTY-NOTICES.txt";
    private const string NotStated = "not stated by the package";

    public static string Write(IEnumerable<Part> parts, Func<string, string?> licenseText)
    {
        var all = parts
            .DistinctBy(part => (part.Source, part.Name.ToUpperInvariant(), part.Version))
            .OrderBy(part => part.Name, StringComparer.OrdinalIgnoreCase)
            .ThenBy(part => part.Name, StringComparer.Ordinal)
            .ThenBy(part => part.Version, StringComparer.Ordinal)
            .ToList();

        var text = new StringBuilder();
        Heading(text, "ComParta third-party notices", '=');
        text.Append("ComParta is released under the Zero-Clause BSD license (see LICENSE).\n");
        text.Append("It includes the parts below, each under its own license.\n");
        text.Append("Generated by tools/ComParta.Notices. Do not edit by hand.\n\n");

        Section(text, "Parts in the app and the helper (NuGet)", all.Where(part => part.Source == PartSource.NuGet));
        Section(text, "Parts in the screen (npm)", all.Where(part => part.Source == PartSource.Npm));

        Heading(text, "License texts", '-');
        var ids = all.Where(part => part.License is not null)
            .SelectMany(part => LicensePolicy.AllowedIds(part.License!))
            .Distinct(StringComparer.Ordinal)
            .Order(StringComparer.Ordinal);
        var texts = ids.Select(id => (id, licenseText(id))).Where(pair => pair.Item2 is not null)
            .Select(pair => $"== {pair.id} ==\n{pair.Item2!.ReplaceLineEndings("\n").Trim()}\n");
        text.Append(string.Join("\n", texts));
        return text.ToString().TrimEnd('\n') + "\n";
    }

    private static void Section(StringBuilder text, string title, IEnumerable<Part> parts)
    {
        Heading(text, title, '-');
        foreach (var part in parts)
        {
            text.Append($"{part.Name} {part.Version}\n");
            text.Append($"License: {part.License ?? NotStated}\n");
            text.Append($"Copyright: {part.Copyright ?? NotStated}\n");
            text.Append($"Project: {part.ProjectUrl ?? NotStated}\n\n");
        }
    }

    private static void Heading(StringBuilder text, string title, char underline) =>
        text.Append(title).Append('\n').Append(underline, title.Length).Append("\n\n");

    /// <summary>The standard text of an allowed license, kept in LicenseTexts.</summary>
    public static string? StandardText(string id)
    {
        using var stream = typeof(NoticesWriter).Assembly.GetManifestResourceStream($"LicenseTexts.{id}.txt");
        if (stream is null)
            return null;
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd();
    }

    /// <summary>
    /// Null when the committed text matches the fresh one (line endings aside), otherwise the first lines
    /// that differ, to print.
    /// </summary>
    public static string? Difference(string? committed, string fresh)
    {
        var wanted = fresh.ReplaceLineEndings("\n");
        if (committed?.ReplaceLineEndings("\n") == wanted)
            return null;
        if (committed is null)
            return $"{FileName} is missing.";

        var had = committed.ReplaceLineEndings("\n").Split('\n');
        var now = wanted.Split('\n');
        var differences = new List<string>();
        for (var i = 0; i < Math.Max(had.Length, now.Length) && differences.Count < 10; i++)
        {
            var before = i < had.Length ? had[i] : "(nothing)";
            var after = i < now.Length ? now[i] : "(nothing)";
            if (before != after)
                differences.Add($"line {i + 1}: committed \"{before}\", now \"{after}\"");
        }
        return string.Join("\n", differences);
    }
}
